CREATE TABLE experiments (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT NOT NULL,
    investigation_id      BIGINT NOT NULL,
    goal_id               BIGINT NOT NULL,
    hypothesis            TEXT NOT NULL,
    baseline_start_date   DATE NOT NULL,
    baseline_end_date     DATE NOT NULL,
    duration_days         INTEGER NOT NULL,
    intervention           JSONB NOT NULL,
    primary_metric        VARCHAR(64) NOT NULL,
    secondary_metrics     JSONB NOT NULL DEFAULT '[]'::jsonb,
    stop_conditions       JSONB NOT NULL,
    outcome_direction     VARCHAR(16) NOT NULL,
    meaningful_change     NUMERIC NOT NULL,
    status                VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    aggregate_version     BIGINT NOT NULL DEFAULT 0,
    accepted_at           TIMESTAMPTZ,
    started_at            TIMESTAMPTZ,
    rejected_at           TIMESTAMPTZ,
    aborted_at            TIMESTAMPTZ,
    completed_at          TIMESTAMPTZ,
    evaluated_at          TIMESTAMPTZ,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_experiments_user_id UNIQUE (user_id, id),
    CONSTRAINT fk_experiments_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_experiments_investigation FOREIGN KEY (user_id, investigation_id)
        REFERENCES investigations(user_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_experiments_goal FOREIGN KEY (user_id, goal_id)
        REFERENCES goals(user_id, id) ON DELETE CASCADE,
    CONSTRAINT chk_experiments_status CHECK (status IN (
        'DRAFT', 'PROPOSED', 'ACCEPTED', 'REJECTED', 'ACTIVE', 'PAUSED',
        'COMPLETED', 'ABORTED', 'EVALUATED')),
    CONSTRAINT chk_experiments_hypothesis_not_blank CHECK (length(trim(hypothesis)) BETWEEN 1 AND 4000),
    CONSTRAINT chk_experiments_baseline_window CHECK (
        baseline_end_date >= baseline_start_date
        AND baseline_end_date - baseline_start_date BETWEEN 0 AND 89),
    CONSTRAINT chk_experiments_duration CHECK (duration_days BETWEEN 1 AND 90),
    CONSTRAINT chk_experiments_primary_metric_not_blank CHECK (length(trim(primary_metric)) BETWEEN 1 AND 64),
    CONSTRAINT chk_experiments_version CHECK (aggregate_version >= 0),
    CONSTRAINT chk_experiments_intervention CHECK (
        jsonb_typeof(intervention) = 'object'
        AND intervention @> '{"primary": true}'::jsonb
        AND jsonb_typeof(intervention -> 'primary') = 'boolean'
        AND intervention ? 'action' AND intervention ? 'protocol'
        AND length(trim(intervention ->> 'action')) BETWEEN 1 AND 200
        AND length(trim(intervention ->> 'protocol')) BETWEEN 1 AND 2000),
    CONSTRAINT chk_experiments_secondary_metrics CHECK (jsonb_typeof(secondary_metrics) = 'array'),
    CONSTRAINT chk_experiments_stop_conditions CHECK (
        jsonb_typeof(stop_conditions) = 'array' AND jsonb_array_length(stop_conditions) >= 1),
    CONSTRAINT chk_experiments_outcome_direction CHECK (
        outcome_direction IN ('INCREASE', 'DECREASE', 'MAINTAIN')),
    CONSTRAINT chk_experiments_meaningful_change CHECK (
        meaningful_change > 0 AND meaningful_change <= 1000000),
    CONSTRAINT chk_experiments_draft_proposed_timestamps CHECK (
        status NOT IN ('DRAFT', 'PROPOSED')
        OR (accepted_at IS NULL AND started_at IS NULL AND rejected_at IS NULL
            AND aborted_at IS NULL AND completed_at IS NULL AND evaluated_at IS NULL)),
    CONSTRAINT chk_experiments_accepted_timestamp CHECK (
        status NOT IN ('ACCEPTED', 'ACTIVE', 'PAUSED', 'COMPLETED', 'EVALUATED')
        OR accepted_at IS NOT NULL),
    CONSTRAINT chk_experiments_accepted_lifecycle CHECK (
        status <> 'ACCEPTED'
        OR (started_at IS NULL AND rejected_at IS NULL AND aborted_at IS NULL
            AND completed_at IS NULL AND evaluated_at IS NULL)),
    CONSTRAINT chk_experiments_started_timestamp CHECK (
        status NOT IN ('ACTIVE', 'PAUSED', 'COMPLETED', 'EVALUATED')
        OR started_at IS NOT NULL),
    CONSTRAINT chk_experiments_active_lifecycle CHECK (
        status NOT IN ('ACTIVE', 'PAUSED')
        OR (rejected_at IS NULL AND aborted_at IS NULL AND completed_at IS NULL
            AND evaluated_at IS NULL)),
    CONSTRAINT chk_experiments_rejected_timestamps CHECK (
        status <> 'REJECTED'
        OR (rejected_at IS NOT NULL AND accepted_at IS NULL AND started_at IS NULL
            AND aborted_at IS NULL AND completed_at IS NULL AND evaluated_at IS NULL)),
    CONSTRAINT chk_experiments_aborted_timestamps CHECK (
        status <> 'ABORTED'
        OR (aborted_at IS NOT NULL AND rejected_at IS NULL
            AND completed_at IS NULL AND evaluated_at IS NULL)),
    CONSTRAINT chk_experiments_completed_timestamps CHECK (
        status <> 'COMPLETED'
        OR (completed_at IS NOT NULL AND rejected_at IS NULL
            AND aborted_at IS NULL AND evaluated_at IS NULL)),
    CONSTRAINT chk_experiments_evaluated_timestamps CHECK (
        status <> 'EVALUATED'
        OR (completed_at IS NOT NULL AND evaluated_at IS NOT NULL
            AND rejected_at IS NULL AND aborted_at IS NULL))
);

CREATE INDEX idx_experiments_user_status
    ON experiments(user_id, status, updated_at DESC, id);

CREATE UNIQUE INDEX uq_experiments_one_in_flight
    ON experiments(user_id)
    WHERE status IN ('ACCEPTED', 'ACTIVE', 'PAUSED');

CREATE TABLE experiment_transitions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL,
    experiment_id     BIGINT NOT NULL,
    from_status       VARCHAR(32) NOT NULL,
    to_status         VARCHAR(32) NOT NULL,
    expected_version  BIGINT NOT NULL,
    result_version    BIGINT NOT NULL,
    reason            VARCHAR(500),
    occurred_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_experiment_transitions_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_experiment_transitions_experiment FOREIGN KEY (user_id, experiment_id)
        REFERENCES experiments(user_id, id) ON DELETE CASCADE,
    CONSTRAINT chk_experiment_transitions_from_status CHECK (from_status IN (
        'DRAFT', 'PROPOSED', 'ACCEPTED', 'REJECTED', 'ACTIVE', 'PAUSED',
        'COMPLETED', 'ABORTED', 'EVALUATED')),
    CONSTRAINT chk_experiment_transitions_to_status CHECK (to_status IN (
        'DRAFT', 'PROPOSED', 'ACCEPTED', 'REJECTED', 'ACTIVE', 'PAUSED',
        'COMPLETED', 'ABORTED', 'EVALUATED')),
    CONSTRAINT chk_experiment_transitions_version CHECK (
        expected_version >= 0 AND result_version = expected_version + 1),
    CONSTRAINT chk_experiment_transitions_reason CHECK (
        reason IS NULL OR length(trim(reason)) BETWEEN 1 AND 500),
    CONSTRAINT chk_experiment_transitions_legal_edge CHECK (
        (from_status = 'DRAFT' AND to_status = 'PROPOSED')
        OR (from_status = 'PROPOSED' AND to_status IN ('ACCEPTED', 'REJECTED'))
        OR (from_status = 'ACCEPTED' AND to_status IN ('ACTIVE', 'ABORTED'))
        OR (from_status = 'ACTIVE' AND to_status IN ('PAUSED', 'COMPLETED', 'ABORTED'))
        OR (from_status = 'PAUSED' AND to_status IN ('ACTIVE', 'COMPLETED', 'ABORTED'))
        OR (from_status = 'COMPLETED' AND to_status = 'EVALUATED'))
);

CREATE INDEX idx_experiment_transitions_owner_experiment
    ON experiment_transitions(user_id, experiment_id, id);
