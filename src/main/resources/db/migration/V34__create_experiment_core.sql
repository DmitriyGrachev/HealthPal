CREATE TABLE investigations (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL,
    title              VARCHAR(160) NOT NULL,
    problem_statement  VARCHAR(4000) NOT NULL,
    status             VARCHAR(32) NOT NULL DEFAULT 'OPEN',
    aggregate_version  BIGINT NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_investigations_user_id UNIQUE (user_id, id),
    CONSTRAINT fk_investigations_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT chk_investigations_title_not_blank CHECK (length(trim(title)) BETWEEN 1 AND 160),
    CONSTRAINT chk_investigations_problem_not_blank CHECK (length(trim(problem_statement)) BETWEEN 1 AND 4000),
    CONSTRAINT chk_investigations_status CHECK (status IN
        ('OPEN', 'COLLECTING_BASELINE', 'READY_FOR_EXPERIMENT', 'EXPERIMENTING', 'RESOLVED', 'ARCHIVED')),
    CONSTRAINT chk_investigations_version CHECK (aggregate_version >= 0)
);

CREATE INDEX idx_investigations_user_status ON investigations(user_id, status, updated_at DESC);

CREATE TABLE goals (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL,
    investigation_id   BIGINT,
    superseded_goal_id BIGINT,
    type               VARCHAR(32) NOT NULL,
    name               VARCHAR(160) NOT NULL,
    metric             VARCHAR(32) NOT NULL,
    target_min         NUMERIC(18,6),
    target_max         NUMERIC(18,6),
    target_unit        VARCHAR(32),
    status             VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    deadline           DATE,
    priority           INTEGER NOT NULL DEFAULT 0,
    source             VARCHAR(32) NOT NULL,
    is_primary         BOOLEAN NOT NULL DEFAULT FALSE,
    aggregate_version  BIGINT NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at       TIMESTAMPTZ,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_goals_user_id UNIQUE (user_id, id),
    CONSTRAINT fk_goals_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_goals_investigation FOREIGN KEY (user_id, investigation_id)
        REFERENCES investigations(user_id, id) ON DELETE SET NULL (investigation_id),
    CONSTRAINT fk_goals_superseded FOREIGN KEY (user_id, superseded_goal_id)
        REFERENCES goals(user_id, id) ON DELETE SET NULL (superseded_goal_id),
    CONSTRAINT chk_goals_status CHECK (status IN ('DRAFT', 'ACTIVE', 'PAUSED', 'ACHIEVED', 'ABANDONED', 'SUPERSEDED')),
    CONSTRAINT chk_goals_type CHECK (type IN ('WEIGHT_LOSS', 'MUSCLE_GAIN', 'MAINTENANCE', 'PERFORMANCE', 'HEALTH', 'HABIT', 'CUSTOM')),
    CONSTRAINT chk_goals_metric CHECK (metric IN ('WEIGHT', 'BODY_FAT', 'STRENGTH', 'VOLUME', 'CALORIES', 'FREQUENCY', 'CUSTOM')),
    CONSTRAINT chk_goals_source CHECK (source IN ('USER', 'IMPORTED', 'SYSTEM', 'AI_DRAFT')),
    CONSTRAINT chk_goals_priority CHECK (priority BETWEEN 0 AND 1000),
    CONSTRAINT chk_goals_version CHECK (aggregate_version >= 0),
    CONSTRAINT chk_goals_name_not_blank CHECK (length(trim(name)) BETWEEN 1 AND 160),
    CONSTRAINT chk_goals_target_bounds CHECK (target_min IS NULL OR target_max IS NULL OR target_min <= target_max),
    CONSTRAINT chk_goals_target_unit CHECK ((target_min IS NULL AND target_max IS NULL AND target_unit IS NULL)
        OR ((target_min IS NOT NULL OR target_max IS NOT NULL)
            AND target_unit IS NOT NULL AND length(trim(target_unit)) BETWEEN 1 AND 32))
);

CREATE INDEX idx_goals_user_status ON goals(user_id, status, priority, updated_at DESC);
CREATE UNIQUE INDEX uq_goals_one_primary_active
    ON goals(user_id)
    WHERE is_primary = TRUE AND status = 'ACTIVE';

CREATE TABLE experiment_command_receipts (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL,
    aggregate_type     VARCHAR(32) NOT NULL,
    aggregate_id       BIGINT NOT NULL,
    idempotency_key    VARCHAR(128) NOT NULL,
    request_fingerprint VARCHAR(64) NOT NULL,
    result_version     BIGINT NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_experiment_command_receipts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT chk_experiment_receipt_type CHECK (aggregate_type ~ '^[A-Z][A-Z0-9_]{0,31}$'),
    CONSTRAINT chk_experiment_receipt_aggregate_id CHECK (aggregate_id > 0),
    CONSTRAINT chk_experiment_receipt_key_not_blank CHECK (length(trim(idempotency_key)) BETWEEN 1 AND 128),
    CONSTRAINT chk_experiment_receipt_fingerprint CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_experiment_receipt_version CHECK (result_version >= 0),
    CONSTRAINT uq_experiment_receipt_owner_command UNIQUE (user_id, aggregate_type, idempotency_key)
);

CREATE INDEX idx_experiment_command_receipts_aggregate
    ON experiment_command_receipts(user_id, aggregate_type, aggregate_id);
