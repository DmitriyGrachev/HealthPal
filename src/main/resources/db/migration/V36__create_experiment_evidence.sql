CREATE TABLE experiment_check_ins (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT NOT NULL,
    experiment_id        BIGINT NOT NULL,
    local_date           DATE NOT NULL,
    timezone             VARCHAR(64) NOT NULL,
    scheduled_start_at   TIMESTAMPTZ,
    scheduled_end_at     TIMESTAMPTZ,
    adherence_status     VARCHAR(16) NOT NULL,
    adherence_value      NUMERIC(18,6),
    deviation_reason     VARCHAR(500),
    note                 VARCHAR(500),
    readiness            SMALLINT,
    sleep                SMALLINT,
    mood                 SMALLINT,
    source               VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    recorded_at          TIMESTAMPTZ NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_experiment_check_ins_user_id UNIQUE (user_id, id),
    CONSTRAINT fk_experiment_check_ins_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_experiment_check_ins_experiment FOREIGN KEY (user_id, experiment_id)
        REFERENCES experiments(user_id, id) ON DELETE CASCADE,
    CONSTRAINT uq_experiment_check_ins_experiment_date UNIQUE (experiment_id, local_date),
    CONSTRAINT chk_experiment_check_ins_timezone CHECK (
        length(trim(timezone)) BETWEEN 1 AND 64),
    CONSTRAINT chk_experiment_check_ins_adherence CHECK (
        adherence_status IN ('YES', 'NO', 'PARTIAL', 'UNKNOWN')),
    CONSTRAINT chk_experiment_check_ins_adherence_value CHECK (
        adherence_value IS NULL OR adherence_value BETWEEN -1000000000 AND 1000000000),
    CONSTRAINT chk_experiment_check_ins_schedule CHECK (
        scheduled_end_at IS NULL OR scheduled_start_at IS NULL OR scheduled_end_at >= scheduled_start_at),
    CONSTRAINT chk_experiment_check_ins_deviation_reason CHECK (
        deviation_reason IS NULL OR length(trim(deviation_reason)) BETWEEN 1 AND 500),
    CONSTRAINT chk_experiment_check_ins_note CHECK (
        note IS NULL OR length(trim(note)) BETWEEN 1 AND 500),
    CONSTRAINT chk_experiment_check_ins_readiness CHECK (
        readiness IS NULL OR readiness BETWEEN 0 AND 10),
    CONSTRAINT chk_experiment_check_ins_sleep CHECK (
        sleep IS NULL OR sleep BETWEEN 0 AND 10),
    CONSTRAINT chk_experiment_check_ins_mood CHECK (
        mood IS NULL OR mood BETWEEN 0 AND 10),
    CONSTRAINT chk_experiment_check_ins_source CHECK (
        source IN ('MANUAL', 'IMPORTED', 'INFERRED'))
);

CREATE INDEX idx_experiment_check_ins_owner_experiment_date
    ON experiment_check_ins(user_id, experiment_id, local_date);

CREATE TABLE experiment_outcomes (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT NOT NULL,
    experiment_id         BIGINT NOT NULL,
    metric_key            VARCHAR(64) NOT NULL,
    baseline_value        NUMERIC(18,6) NOT NULL,
    observed_value        NUMERIC(18,6) NOT NULL,
    unit                  VARCHAR(32) NOT NULL,
    baseline_sample_count INTEGER NOT NULL,
    observed_sample_count INTEGER NOT NULL,
    observed_at           TIMESTAMPTZ NOT NULL,
    source                VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    note                  VARCHAR(1000),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_experiment_outcomes_user_id UNIQUE (user_id, id),
    CONSTRAINT fk_experiment_outcomes_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_experiment_outcomes_experiment FOREIGN KEY (user_id, experiment_id)
        REFERENCES experiments(user_id, id) ON DELETE CASCADE,
    CONSTRAINT uq_experiment_outcomes_experiment UNIQUE (experiment_id),
    CONSTRAINT chk_experiment_outcomes_metric_key CHECK (
        length(trim(metric_key)) BETWEEN 1 AND 64),
    CONSTRAINT chk_experiment_outcomes_unit CHECK (
        length(trim(unit)) BETWEEN 1 AND 32),
    CONSTRAINT chk_experiment_outcomes_values CHECK (
        baseline_value BETWEEN -1000000000 AND 1000000000
        AND observed_value BETWEEN -1000000000 AND 1000000000),
    CONSTRAINT chk_experiment_outcomes_sample_counts CHECK (
        baseline_sample_count >= 1 AND observed_sample_count >= 1),
    CONSTRAINT chk_experiment_outcomes_source CHECK (
        source IN ('MANUAL', 'IMPORTED', 'INFERRED')),
    CONSTRAINT chk_experiment_outcomes_note CHECK (
        note IS NULL OR length(trim(note)) BETWEEN 1 AND 1000)
);

CREATE INDEX idx_experiment_outcomes_owner_experiment
    ON experiment_outcomes(user_id, experiment_id);

CREATE TABLE experiment_evaluations (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT NOT NULL,
    experiment_id         BIGINT NOT NULL,
    formula_version       VARCHAR(32) NOT NULL DEFAULT 'V1',
    recommended_decision  VARCHAR(16) NOT NULL,
    data_quality          VARCHAR(16) NOT NULL,
    observed_effect       VARCHAR(16) NOT NULL,
    confounder_assessment VARCHAR(24) NOT NULL,
    effect_delta          NUMERIC(18,6),
    effect_threshold      NUMERIC(18,6),
    coverage              NUMERIC(6,5),
    adherence             NUMERIC(6,5),
    freshness_days        INTEGER,
    calculation_inputs    JSONB NOT NULL,
    reason_codes          TEXT[] NOT NULL,
    evaluated_at          TIMESTAMPTZ NOT NULL,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_experiment_evaluations_user_id UNIQUE (user_id, id),
    CONSTRAINT fk_experiment_evaluations_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_experiment_evaluations_experiment FOREIGN KEY (user_id, experiment_id)
        REFERENCES experiments(user_id, id) ON DELETE CASCADE,
    CONSTRAINT uq_experiment_evaluations_experiment UNIQUE (experiment_id),
    CONSTRAINT chk_experiment_evaluations_formula_version CHECK (
        length(trim(formula_version)) BETWEEN 1 AND 32),
    CONSTRAINT chk_experiment_evaluations_decision CHECK (
        recommended_decision IN ('KEEP', 'MODIFY', 'DROP', 'INCONCLUSIVE')),
    CONSTRAINT chk_experiment_evaluations_quality CHECK (
        data_quality IN ('SUFFICIENT', 'INSUFFICIENT')),
    CONSTRAINT chk_experiment_evaluations_effect CHECK (
        observed_effect IN ('POSITIVE', 'NEUTRAL', 'NEGATIVE', 'UNKNOWN')),
    CONSTRAINT chk_experiment_evaluations_confounder CHECK (
        confounder_assessment IN ('NONE', 'PRESENT_RESOLVED', 'UNRESOLVED')),
    CONSTRAINT chk_experiment_evaluations_threshold CHECK (
        effect_threshold IS NULL OR (effect_threshold > 0 AND effect_threshold <= 1000000)),
    CONSTRAINT chk_experiment_evaluations_coverage CHECK (
        coverage IS NULL OR coverage BETWEEN 0 AND 1),
    CONSTRAINT chk_experiment_evaluations_adherence CHECK (
        adherence IS NULL OR adherence BETWEEN 0 AND 1),
    CONSTRAINT chk_experiment_evaluations_freshness CHECK (
        freshness_days IS NULL OR freshness_days >= 0),
    CONSTRAINT chk_experiment_evaluations_inputs CHECK (
        jsonb_typeof(calculation_inputs) = 'object'),
    CONSTRAINT chk_experiment_evaluations_reason_codes CHECK (
        cardinality(reason_codes) >= 1)
);

CREATE INDEX idx_experiment_evaluations_owner_decision
    ON experiment_evaluations(user_id, recommended_decision);

CREATE TABLE experiment_decisions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL,
    experiment_id  BIGINT NOT NULL,
    evaluation_id  BIGINT NOT NULL,
    decision       VARCHAR(16) NOT NULL,
    note           VARCHAR(500),
    decided_at     TIMESTAMPTZ NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_experiment_decisions_user_id UNIQUE (user_id, id),
    CONSTRAINT fk_experiment_decisions_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_experiment_decisions_experiment FOREIGN KEY (user_id, experiment_id)
        REFERENCES experiments(user_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_experiment_decisions_evaluation FOREIGN KEY (user_id, evaluation_id)
        REFERENCES experiment_evaluations(user_id, id) ON DELETE CASCADE,
    CONSTRAINT uq_experiment_decisions_experiment UNIQUE (experiment_id),
    CONSTRAINT chk_experiment_decisions_decision CHECK (
        decision IN ('KEEP', 'MODIFY', 'DROP', 'INCONCLUSIVE')),
    CONSTRAINT chk_experiment_decisions_note CHECK (
        note IS NULL OR length(trim(note)) BETWEEN 1 AND 500)
);

CREATE INDEX idx_experiment_decisions_owner_decision
    ON experiment_decisions(user_id, decision);

CREATE TABLE experiment_evidence_refs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    experiment_id   BIGINT NOT NULL,
    purpose         VARCHAR(24) NOT NULL,
    source_type     VARCHAR(32) NOT NULL,
    source_id       VARCHAR(128) NOT NULL,
    source_version  BIGINT NOT NULL,
    content_hash    CHAR(64) NOT NULL,
    source_date     DATE,
    observed_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_experiment_evidence_refs_user_id UNIQUE (user_id, id),
    CONSTRAINT fk_experiment_evidence_refs_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_experiment_evidence_refs_experiment FOREIGN KEY (user_id, experiment_id)
        REFERENCES experiments(user_id, id) ON DELETE CASCADE,
    CONSTRAINT uq_experiment_evidence_refs_identity UNIQUE (
        user_id, experiment_id, purpose, source_type, source_id, source_version, content_hash),
    CONSTRAINT chk_experiment_evidence_refs_purpose CHECK (
        purpose IN ('BASELINE', 'INTERVENTION', 'OUTCOME', 'CONFOUNDER')),
    CONSTRAINT chk_experiment_evidence_refs_source_type CHECK (
        source_type IN ('NUTRITION_DAY', 'WORKOUT_DAY', 'MANUAL_CHECK_IN', 'MANUAL_OUTCOME')),
    CONSTRAINT chk_experiment_evidence_refs_source_id CHECK (
        length(trim(source_id)) BETWEEN 1 AND 128),
    CONSTRAINT chk_experiment_evidence_refs_source_version CHECK (source_version > 0),
    CONSTRAINT chk_experiment_evidence_refs_hash CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_experiment_evidence_refs_observed_source CHECK (
        source_date IS NOT NULL OR observed_at IS NOT NULL)
);

CREATE INDEX idx_experiment_evidence_refs_owner_experiment_purpose
    ON experiment_evidence_refs(user_id, experiment_id, purpose);
